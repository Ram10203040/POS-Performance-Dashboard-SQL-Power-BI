DROP DATABASE IF EXISTS insurance_practice;
CREATE DATABASE insurance_practice CHARACTER SET utf8mb4;
USE insurance_practice;

CREATE TABLE customer (
  customer_id INT PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  dob         DATE,
  city        VARCHAR(50),
  state       VARCHAR(50)
);

CREATE TABLE policy (
  policy_no     VARCHAR(15) PRIMARY KEY,
  customer_id   INT NOT NULL,
  plan_code     VARCHAR(20),
  status        VARCHAR(20),      -- In Force, Lapsed, Paid-up, Surrendered, Matured
  issue_date    DATE,
  sum_assured   DECIMAL(12,2),
  premium       DECIMAL(10,2),
  premium_mode  VARCHAR(15),      -- Monthly, Quarterly, Half-Yearly, Yearly
  FOREIGN KEY (customer_id) REFERENCES customer(customer_id)
);

CREATE TABLE pos_request (
  request_id     INT PRIMARY KEY,
  policy_no      VARCHAR(15) NOT NULL,
  request_type   VARCHAR(30),
  channel        VARCHAR(20),
  received_date  DATE,
  closed_date    DATE NULL,       -- NULL while Pending
  status         VARCHAR(15),     -- Closed, Pending, Rejected
  stp_flag       CHAR(1),         -- Y = straight-through, N = manual touch
  reject_reason  VARCHAR(50) NULL,
  FOREIGN KEY (policy_no) REFERENCES policy(policy_no)
);

CREATE TABLE premium_payment (
  payment_id  INT PRIMARY KEY,
  policy_no   VARCHAR(15) NOT NULL,
  due_date    DATE,
  paid_date   DATE NULL,          -- NULL = not paid
  amount      DECIMAL(10,2),
  FOREIGN KEY (policy_no) REFERENCES policy(policy_no)
);

CREATE INDEX idx_req_policy ON pos_request(policy_no);
CREATE INDEX idx_req_received ON pos_request(received_date);
CREATE INDEX idx_pay_policy ON premium_payment(policy_no);

